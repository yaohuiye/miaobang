// Offline audio generation: see docs/BUILD.md for Python, Piper voice and FFmpeg setup.
import { createHash } from 'node:crypto'
import { mkdirSync, mkdtempSync, writeFileSync, rmSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'
import { tmpdir } from 'node:os'
import { spawn } from 'node:child_process'
import { english } from '../data/knowledge/english.mjs'
const root = fileURLToPath(new URL('../', import.meta.url))
const model = process.argv[2]
if (!model) throw new Error('Usage: node scripts/build-english-audio.mjs /path/to/en_US-ljspeech-high.onnx')
const voiceKey = 'piper-1.8.0:en_US-ljspeech-high:5d4f08ba6a2a48c44592eed3ce56bf85e9de3dd4e20df90541ae68a8310c029a:1.1'
const output = join(root, 'static/english')
const temporary = mkdtempSync(join(tmpdir(), 'miaobang-english-'))
mkdirSync(output, { recursive: true })
const tasks = new Map()
const manifest = Object.fromEntries(english.map(entry => [entry.id, Object.fromEntries([
  ['word', entry.title], ['example', entry.example.split('\n')[0]]
].map(([kind, text]) => {
  const hash = createHash('sha256').update(`${voiceKey}:${text}`).digest('hex').slice(0, 16)
  tasks.set(hash, text)
  return [kind, { text, src: `/static/english/${hash}.m4a` }]
}))]))
try {
  const taskFile = join(temporary, 'tasks.json')
  writeFileSync(taskFile, JSON.stringify([...tasks]))
  await new Promise((resolve, reject) => {
    const child = spawn(process.env.PIPER_PYTHON || 'python3', [join(root, 'scripts/render-english-audio.py'), model, taskFile, output, temporary], { stdio: 'inherit' })
    child.on('error', reject)
    child.on('exit', code => code === 0 ? resolve() : reject(new Error(`Audio generation failed (${code})`)))
  })
  writeFileSync(join(root, 'data/knowledge/english-audio.mjs'), `// Generated by scripts/build-english-audio.mjs.\n// Piper 1.8.0 / en_US-ljspeech-high, length_scale 1.1; AAC mono.\nexport const ENGLISH_AUDIO = ${JSON.stringify(manifest, null, 2)}\n`)
  console.log(`Ready: ${english.length} cards, ${tasks.size} audio files.`)
} finally {
  rmSync(temporary, { recursive: true, force: true })
}
